using System;
using CoopSpectator.Infrastructure;
using CoopSpectator.Network.Messages;

internal static class BattleContentTransportTests
{
    internal static void Run()
    {
        foreach (string kind in new[] { "Field", "Village", "Hideout", "Siege", "LordsHall", "SiegeAmbush", "Relief" })
        {
            string profile = "naval-v1:" + new string('c',64);
            var snapshot = new BattleSnapshotMessage {
                BattleId = "content-transport-fixture", MapScene = "battle_terrain_029", WorldMapScene = "Main_map",
                ScenarioContext = new BattleScenarioContextMessage { ContentProfileId = profile, ScenarioKind = kind,
                    IsSiegeBattle = kind == "Siege" || kind == "LordsHall", Source = "contract-test",
                    SiegeContext = kind == "Field" ? null : new BattleSiegeContextMessage { SiegeSubtype = kind } } };
            snapshot.CraftedWeapons.Add(new CraftedWeaponSnapshotMessage { Key = "naval-fixture", CraftingTemplateId = "TwoHandedAxe",
                Pieces = { new CraftedWeaponPieceSnapshotMessage { PieceId = "naval_axe_head_08", PieceType = "Blade", ScalePercentage = 100 } } });
            Check(BattleSnapshotBinarySerializer.TrySerialize(snapshot, out var payload) && BitConverter.ToInt32(payload,4) == 20,
                kind + " uses content-aware binary schema");
            Check(BattleSnapshotBinarySerializer.TryDeserialize(payload, out var received) &&
                received.ScenarioContext.ContentProfileId == profile && received.ScenarioContext.Clone().ContentProfileId == profile &&
                received.ScenarioContext.ScenarioKind == kind && received.CraftedWeapons[0].Pieces[0].PieceId == "naval_axe_head_08",
                kind + " retains content ownership and exact crafted dependency across the real snapshot serializer");
        }
        // Generated by the actual af-b2/schema19 serializer, not by rewriting
        // the new header. Legacy data stays readable but is never guessed Base.
        byte[] legacy = Convert.FromBase64String("MUJTQxMAAAABEGxlZ2FjeTE5LWZpeHR1cmUAAAAAAAIAAAAAAAAAAAAAARJiYXR0bGVfdGVycmFpbl8wMjkA/////wAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAIA/AAAAgL8AAAEAAQVGaWVsZAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA");
        Check(BattleSnapshotBinarySerializer.TryDeserialize(legacy, out var old) &&
            old.BattleId == "legacy19-fixture" && old.ScenarioContext.ScenarioKind == "Field" &&
            string.IsNullOrEmpty(old.ScenarioContext.ContentProfileId), "real schema19 fixture remains readable and explicitly unbound");
        Console.WriteLine("PASS content-aware binary battle snapshot transport: seven scenario shapes, schema20, exact Naval crafted dependency.");
    }
    private static void Check(bool value, string message) { if (!value) throw new InvalidOperationException(message); }
}

